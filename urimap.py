### URI Mapper ###

def mapper(length):
    """Function that takes URIs from the list generated by DSI and turns into a keymap"""
    global URImap
    # global -> local

    num = 0
    # starts at 0
    hasErrored = False
    # boolean to check if the program encountered an unskippable error

    for uri in unMappedURIs:
    # gets the URI (track ID) for every unmapped URI

        if num == 0:
        # prints on the first URI of the batch
            print(f"{Time()} [UMAP]: URI mapping started")

        if num % 10 == 0:
        # prints every 10 URIs
            print(f"{Time()} [UMAP]: Mapping process: {num} / {length}")

        num += 1
        # adds 1 to the number (QoL)

        try:
        # tries to find it via Spotify
            trackInfo = main.track(uri, MarketArea)
            # requests the track data from Spotify with the ID and market ID
            altURI = f"spotify:track:{trackInfo["id"]}"
            # it stores the "alternate URI" (the ID spotify returns for your market) as a string
            if uri in URImap:
            # if the URI is already in the stored map

                if isinstance(URImap[uri], dict):
                # if the stored entry for the URI is a dictionary (new system), not a string (old system)
                    
                    if "Song Name" not in URImap[uri]:
                    # if there's no stored song name entry yet
                        URImap[uri]["Song Name"] = noURImap[uri]["Song Name"]
                        URImap[uri]["Artist"] = noURImap[uri]["Artist"]
                        # grabs the song name and artist from the new unmapped items

                    if altURI not in URImap[uri].get("URIs", []):
                    # if the found URI is not yet stored in the list of alternate URIs
                        URImap[uri].setdefault("URIs", []).append(altURI)
                        # calls setdefault to either use the existing list or create a new one

                else:
                # not a dict (-> string) = old system
                    oldAltURI = URImap[uri]
                    # grabs the stored old alt URI

                    URImap[uri] = {
                        "URIs": [oldAltURI],
                        "Song Name": noURImap[uri]["Song Name"],
                        "Artist": noURImap[uri]["Artist"]
                    }
                    # stores the entry for this URI with the old URI stored as a list of URIs

                    if altURI not in URImap[uri]["URIs"]:
                    # checks if the newly discovered alt URI is not yet in the list (ensuring no double-save)
                        URImap[uri]["URIs"].append(altURI)
                        # adds the new alt URI
            else:
            # URI not yet in map
                URImap[uri] = {
                    "URIs": [altURI],
                    "Song Name": noURImap[uri]["Song Name"],
                    "Artist": noURImap[uri]["Artist"]
                }
                # forms a new nested dictionary with the song's details

        except SpotifyException as error:
        # if it fails, grabs the error

            if error.http_status == 429:
            # if the error is exactly 429 (rate limit)

                print(f"{Time()} [WARN]: Spotify rate limit exceeded, waiting for cooldown")
                # prints the rate limit info

                retryTimer = int(error.headers["Retry-After"])
                # takes the given "retry after" timer and saves it
                returnTime = datetime.datetime.fromtimestamp(int(retryTimer + time.time() + 3)).strftime("%H:%M:%S")
                # gets the return time (time the cooldown expires)

                print(f"{Time()} [WARN]: Rate limit cooldown is {retryTimer} ({returnTime})")
                # prints the cooldown info
                print(f"{Time()} [EXIT]: Exiting app in 10 minutes... (feel free to close)")
                # user inform
                hasErrored = True
                # sets the bool to True
                break
                # stops the for loop
            else:
            # if it's not 429 (anything else is just hard to work around)
                print(f"{Time()} [ERROR]: Spotify API error {error.http_status}")
                # user inform
        
        except PermissionError as error:
        # any firewall/network issue (unfortunately common, while testing at least)

            if getattr(error, "winerror", None) == 10013:
            # if the error is specifically a windows 10013 error (connection blocked for one reason or another)
                print(f"{Time()} [WARN]: Windows has blocked the connection, please check firewall/antivirus settings and retry (WinError 10013)")
                print(f"{Time()} [INFO]: Sometimes this is due to odd Windows behavior, and system restart may fix this")
                print(f"{Time()} [EXIT]: Exiting app... (feel free to close)")
                # spams a few user informs
                hasErrored = True
                # sets the bool to True
                break
                # stops the for loop
            else:
            # if it's something else
                None
                # doesn't do anything
        
        except Exception as error:
        # any other generic error
            print(f"{Time()} [ERROR]: Error storing URI: {error}")
            # user inform

        time.sleep(0.25)
        # safety implementation, to avoid Windows/Spotify rate limits

        if num == (length-1):
        # prints on the last URI of the batch
            print(f"{Time()} [UMAP]: Mapping complete")
            # user inform

    with open(uriPath, "w", encoding="utf-8") as newUri:
        # opens the JSON file in write mode
        json.dump(URImap, newUri, ensure_ascii=False, indent=2)
        # pushes the data from newUri to the JSON file
    
    print(f"{Time()} [UMAP]: URIs saved to file!")
    # user inform on successful save

    if hasErrored:
    # if the program encountered an error
        time.sleep(300)
        # waits 5 minutes
        raise SystemExit
        # closes everything
    else:
    # no errors during batch
        while True:
        # keeps running
            undoneCheck = batchCalc(15)
            # ensures there's no functions running before re-checking
            if not undoneCheck:
            # if there's nothing undone
                break
                # stops



### Mapper Variable Calculation ###

def batchCalc(pause):
    """Function that calculates the batch size of URIs and starts mapper"""
    global unMappedURIs, unMappedListLen, URImap
    # global -> local

    maxLength = 100
    # sets a max worker size of 100 (number Spotify can typically process nicely (even with DSI running))
    # note that very large batches (thousands) may end up causing rate limit issues regardless of a batch

    unMappedURIs = []
    # clears the list every iteration (so that it doesn't double-dip)

    for uri, item in noURImap.items():
    # goes through the URI and data of the unmapped URIs generated by DSI
        unMappedListLen -= 1
        # deducts one from the list length because the URI was checked (whether it gets acted on or not)
        if isinstance(item, dict) and item.get("Song Name") is not None:
        # if the item is a dictionary and the song name has been set (means it's successfully migrated into the new system)
            if (uri not in URImap.keys()) or not (isinstance(URImap[uri], dict)):
            # if the URI is not in the mapped dict yet, or it's stored using the old system
                unMappedURIs.append(uri)
                # adds the URI to the list of unmapped URIs to work on
                if len(unMappedURIs) >= maxLength:
                # ensures the list doesn't get too long (only 100 at a time)
                    break
                    # stops the for loop

    print(f"{Time()} [INFO]: {unMappedListLen} URIs remaining")
    # user inform print on total remaining URIs

    if (len(unMappedURIs)) > 0:
    # if there are URIs to map

        print(f"{Time()} [INFO]: Processing {len(unMappedURIs)} URIs")
        # informs user on number of URIs to process

        if pause != 0:
        # doesn't print on first run
            print(f"{Time()} [INFO]: Waiting {pause} seconds to start... (rate limit avoidance)")
            # quick user update on wait
        time.sleep(pause)
        # sleeps for the parameter-set length (0 at start, a bit after first batch, to slow down API slamming)

        mapper(len(unMappedURIs))
        # starts new task



### Start Argument(s) ###

print(f"{Time()} [UMAP]: Starting URImapper {URIver}")
